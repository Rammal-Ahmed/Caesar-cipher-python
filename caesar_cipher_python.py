# Caesar Cipher
# Shifts each letter by a given amount, wrapping around the alphabet.
# Non-letter characters are left unchanged.


messages = ["Hello, World!", "Khoor, Zruog!", "abc"]
shifts = [3, -3, 29]

alp = "abcdefghijklmnopqrstuvwxyz"

for i in range(len(messages)):
    message = messages[i]
    shift = shifts[i] % 26          # 29 becomes 3, -3 becomes 23
    ans = ""

    for letter in message:
        if letter.lower() in alp:
            position = alp.index(letter.lower())
            new_position = (position + shift) % 26
            new_letter = alp[new_position]

            if letter.isupper():
                new_letter = new_letter.upper()

            ans = ans + new_letter
        else:
            ans = ans + letter

    print(ans)